// Command grammar modules for the lab CLI simulator (pure Dart, no Flutter).
//
// One line = "modes | pattern | flags"
//   modes   comma list: user, priv, config, config-if, config-router, config-line, ...
//           '*' = any mode, 'config*' = any mode starting with "config"
//   pattern tokens: literals, or <num:1-65535> <ip> <mask> <wild> <word> <ifname> <rest>
//   flags   comma list: replace | neg | enter=<mode> | action=<id> | key=<text>
//           replace : a new value replaces the old line with the same leading words
//           neg     : feature that is ON by default; "no X" is stored as the line "no X"
//           enter   : the command opens a block (interface, router ospf ...)
//                     enter=config-router-af / config-vrf-af opens an address-family INSIDE the current block (3rd level)
